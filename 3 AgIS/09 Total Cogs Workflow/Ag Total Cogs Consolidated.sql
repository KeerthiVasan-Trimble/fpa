USE ROLE FIELD_SYSTEMS_DEVELOPER_ROLE;

USE DATABASE FIELD_SYSTEMS_EDW;
USE SCHEMA DISPLAY_AGIS;

USE WAREHOUSE FIELD_SYSTEMS_GENERAL_WAREHOUSE;


CREATE OR REPLACE VIEW FIELD_SYSTEMS_EDW.DISPLAY_AGIS.VIEW_AG_TOTAL_COGS_CONSOLIDATED AS

WITH current_period AS (
    SELECT DISTINCT
        REPLACE(FISCAL_MONTH_CODE, '-M', '-') AS FISCAL_MONTH_CODE
    FROM FIELD_SYSTEMS_EDW.ARCHITECTURAL_COMPONENT.DIMENSION_FISCAL_CALENDAR
    WHERE CALENDAR_DATE = CURRENT_DATE()
),

actuals AS (
    SELECT
        BILLING_MONTH,
        SUM(EXPENDITURE_AMOUNT) AS EXPENDITURE_AMOUNT,
        'ACTUAL' AS SOURCE
    FROM FIELD_SYSTEMS_EDW.WORKFLOW_COMPONENT.DYNAMIC_AG_TOTAL_COGS_ACTUALS
    CROSS JOIN current_period cp
    WHERE BILLING_MONTH < cp.FISCAL_MONTH_CODE
    GROUP BY BILLING_MONTH
),

forecast AS (
    SELECT
        BILLING_MONTH,
        SUM(EXPENDITURE_AMOUNT) AS EXPENDITURE_AMOUNT,
        'FORECAST' AS SOURCE
    FROM FIELD_SYSTEMS_EDW.WORKFLOW_COMPONENT.DYNAMIC_AG_TOTAL_COGS_FORECAST
    CROSS JOIN current_period cp
    WHERE BILLING_MONTH >= cp.FISCAL_MONTH_CODE
    GROUP BY BILLING_MONTH
)

SELECT BILLING_MONTH, EXPENDITURE_AMOUNT, SOURCE
FROM actuals

UNION ALL

SELECT BILLING_MONTH, EXPENDITURE_AMOUNT, SOURCE
FROM forecast

ORDER BY BILLING_MONTH;
