USE ROLE FIELD_SYSTEMS_DEVELOPER_ROLE;

USE DATABASE FIELD_SYSTEMS_EDW;
USE SCHEMA USER_INPUT;

USE WAREHOUSE FIELD_SYSTEMS_GENERAL_WAREHOUSE;



-- CONFIGURATION_AG_RTX (from writeback table SIGDS_4a68a6b9)
CREATE OR REPLACE DYNAMIC TABLE FIELD_SYSTEMS_EDW.USER_INPUT.CONFIGURATION_AG_RTX
(
    RECEIVER_CODE,
    BILLING_MONTH,
    CARVEOUT_PERCENTAGE,
    RATE_PER_UNIT,
    MONTHS_IN_FUTURE,
    MONTH_LAG,
    HALF_MONTH,
    OTHER_BA,
    NATURAL_ACCOUNT
)
LAG = '1 minute'
REFRESH_MODE = FULL
INITIALIZE = ON_CREATE
WAREHOUSE = FIELD_SYSTEMS_GENERAL_WAREHOUSE
AS
SELECT
    "BD6AARRVWR" AS RECEIVER_CODE,
    "I3SLHS_TLU" AS BILLING_MONTH,
    "U77NPINTCP" AS CARVEOUT_PERCENTAGE,
    "_YVMBKEVWG" AS RATE_PER_UNIT,
    "NSC7SBHQII" AS MONTHS_IN_FUTURE,
    "-5HDKNLDGK" AS MONTH_LAG,
    "Z1WJFR6OJU" AS HALF_MONTH,
    "Q_JTLOZXQW" AS OTHER_BA,
    "BDAZ-NXYCG" AS NATURAL_ACCOUNT
FROM FIELD_SYSTEMS_EDW.SIGMA_WRITEBACK."SIGDS_4a68a6b9_d42c_4e9b_9aad_ca76eb449d73"
WHERE "BD6AARRVWR" IS NOT NULL
  AND TOMBSTONE_VERSION IS NULL
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY "BD6AARRVWR"
    ORDER BY UPDATED_AT DESC
) = 1;
