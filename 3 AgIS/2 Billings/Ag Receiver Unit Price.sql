USE ROLE FIELD_SYSTEMS_DEVELOPER_ROLE;

USE DATABASE FIELD_SYSTEMS_EDW;
USE SCHEMA USER_INPUT;

USE WAREHOUSE FIELD_SYSTEMS_GENERAL_WAREHOUSE;

CREATE OR REPLACE DYNAMIC TABLE FIELD_SYSTEMS_EDW.USER_INPUT.DYNAMIC_AG_RECEIVER_UNIT_PRICE
(
    RECEIVER_CODE,
    BILLING_MONTH,
    UNIT_PRICE
)
LAG = '1 minute'
REFRESH_MODE = FULL
INITIALIZE = ON_CREATE
WAREHOUSE = FIELD_SYSTEMS_GENERAL_WAREHOUSE
AS
WITH latest_per_receiver AS (
    SELECT
        "GCPM-XSVDL" AS RECEIVER_CODE,
        "5CUWOFAFS4" AS M01_2026,
        "YNFIZFT49K" AS M02_2026,
        "UKQ9KII9QU" AS M03_2026,
        "56A5ASYPJK" AS M04_2026,
        "WVGWC6MNDF" AS M05_2026,
        "-JHBQBK8AV" AS M06_2026,
        "5GECSDR7A8" AS M07_2026,
        "1WE8S3K8AS" AS M08_2026,
        "KMX80TKCO1" AS M09_2026,
        "SZSC1QSA4A" AS M10_2026,
        "W_2GFTC9U6" AS M11_2026,
        "DY7_LBLGV4" AS M12_2026
    FROM FIELD_SYSTEMS_EDW.SIGMA_WRITEBACK."SIGDS_20d4b72e_23f0_4ca0_a0dc_adba488f0afe"
    WHERE "GCPM-XSVDL" IS NOT NULL
      AND TOMBSTONE_VERSION IS NULL
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY "GCPM-XSVDL"
        ORDER BY UPDATED_AT DESC
    ) = 1
),
unpivoted AS (
    SELECT RECEIVER_CODE, '2026-01' AS BILLING_MONTH, M01_2026 AS UNIT_PRICE FROM latest_per_receiver WHERE M01_2026 IS NOT NULL
    UNION ALL
    SELECT RECEIVER_CODE, '2026-02', M02_2026 FROM latest_per_receiver WHERE M02_2026 IS NOT NULL
    UNION ALL
    SELECT RECEIVER_CODE, '2026-03', M03_2026 FROM latest_per_receiver WHERE M03_2026 IS NOT NULL
    UNION ALL
    SELECT RECEIVER_CODE, '2026-04', M04_2026 FROM latest_per_receiver WHERE M04_2026 IS NOT NULL
    UNION ALL
    SELECT RECEIVER_CODE, '2026-05', M05_2026 FROM latest_per_receiver WHERE M05_2026 IS NOT NULL
    UNION ALL
    SELECT RECEIVER_CODE, '2026-06', M06_2026 FROM latest_per_receiver WHERE M06_2026 IS NOT NULL
    UNION ALL
    SELECT RECEIVER_CODE, '2026-07', M07_2026 FROM latest_per_receiver WHERE M07_2026 IS NOT NULL
    UNION ALL
    SELECT RECEIVER_CODE, '2026-08', M08_2026 FROM latest_per_receiver WHERE M08_2026 IS NOT NULL
    UNION ALL
    SELECT RECEIVER_CODE, '2026-09', M09_2026 FROM latest_per_receiver WHERE M09_2026 IS NOT NULL
    UNION ALL
    SELECT RECEIVER_CODE, '2026-10', M10_2026 FROM latest_per_receiver WHERE M10_2026 IS NOT NULL
    UNION ALL
    SELECT RECEIVER_CODE, '2026-11', M11_2026 FROM latest_per_receiver WHERE M11_2026 IS NOT NULL
    UNION ALL
    SELECT RECEIVER_CODE, '2026-12', M12_2026 FROM latest_per_receiver WHERE M12_2026 IS NOT NULL
)
SELECT
    COALESCE(u.RECEIVER_CODE, d.RECEIVER_CODE) AS RECEIVER_CODE,
    u.BILLING_MONTH,
    u.UNIT_PRICE
FROM unpivoted u
FULL JOIN FIELD_SYSTEMS_EDW.USER_INPUT.DYNAMIC_AG_RECEIVERS_LIST d
    ON u.RECEIVER_CODE = d.RECEIVER_CODE;

