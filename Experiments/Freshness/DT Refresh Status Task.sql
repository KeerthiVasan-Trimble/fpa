-- DT refresh status monitor: auto-refresh task (inserts snapshot every minute)
-- Co-authored with CoCo
USE ROLE FIELD_SYSTEMS_DEVELOPER_ROLE;

USE DATABASE FIELD_SYSTEMS_EDW;
USE SCHEMA GENERAL;

USE WAREHOUSE FIELD_SYSTEMS_GENERAL_WAREHOUSE;

CREATE OR REPLACE TASK FIELD_SYSTEMS_EDW.GENERAL.TASK_REFRESH_DT_STATUS_MONITOR
    WAREHOUSE = FIELD_SYSTEMS_GENERAL_WAREHOUSE
    SCHEDULE = '1 MINUTE'
AS
INSERT INTO FIELD_SYSTEMS_EDW.GENERAL.DT_REFRESH_STATUS_MONITOR (
    DYNAMIC_TABLE_NAME,
    SCHEMA_NAME,
    SCHEDULING_STATE,
    DATA_TIMESTAMP,
    LAST_REFRESH_TIME,
    LAST_REFRESH_STATE,
    SUSPENSION_REASON,
    LAST_REFRESH_STATE_MESSAGE,
    SECONDS_BEHIND,
    CHECKED_AT
)
SELECT
    dt.NAME,
    dt.SCHEMA_NAME,
    dt.SCHEDULING_STATE:state::VARCHAR AS SCHEDULING_STATE,
    dt.LATEST_DATA_TIMESTAMP,
    rh.REFRESH_END_TIME,
    dt.LAST_COMPLETED_REFRESH_STATE,
    dt.SCHEDULING_STATE:reason_message::VARCHAR AS SUSPENSION_REASON,
    dt.LAST_COMPLETED_REFRESH_STATE_MESSAGE,
    DATEDIFF('second', dt.LATEST_DATA_TIMESTAMP, CURRENT_TIMESTAMP()) AS SECONDS_BEHIND,
    CURRENT_TIMESTAMP()
FROM TABLE(FIELD_SYSTEMS_EDW.INFORMATION_SCHEMA.DYNAMIC_TABLES()) dt
LEFT JOIN (
    SELECT
        NAME,
        SCHEMA_NAME,
        REFRESH_END_TIME,
        ROW_NUMBER() OVER (PARTITION BY NAME, SCHEMA_NAME ORDER BY REFRESH_END_TIME DESC) AS RN
    FROM TABLE(FIELD_SYSTEMS_EDW.INFORMATION_SCHEMA.DYNAMIC_TABLE_REFRESH_HISTORY(
        NAME_PREFIX => 'FIELD_SYSTEMS_EDW'
    ))
) rh ON dt.NAME = rh.NAME AND dt.SCHEMA_NAME = rh.SCHEMA_NAME AND rh.RN = 1
ORDER BY dt.SCHEMA_NAME, dt.NAME;

-- Prerequisites (run once as ACCOUNTADMIN):
-- GRANT EXECUTE TASK ON ACCOUNT TO ROLE FIELD_SYSTEMS_DEVELOPER_ROLE;

-- Resume the task:
ALTER TASK FIELD_SYSTEMS_EDW.GENERAL.TASK_REFRESH_DT_STATUS_MONITOR RESUME;
