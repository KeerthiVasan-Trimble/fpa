-- DT refresh status monitor: history/log table
-- Co-authored with CoCo
USE ROLE FIELD_SYSTEMS_DEVELOPER_ROLE;

USE DATABASE FIELD_SYSTEMS_EDW;
USE SCHEMA GENERAL;

USE WAREHOUSE FIELD_SYSTEMS_GENERAL_WAREHOUSE;

CREATE OR REPLACE TABLE FIELD_SYSTEMS_EDW.GENERAL.DT_REFRESH_STATUS_MONITOR (
    DYNAMIC_TABLE_NAME VARCHAR,
    SCHEMA_NAME VARCHAR,
    SCHEDULING_STATE VARCHAR,
    DATA_TIMESTAMP TIMESTAMP_TZ,
    LAST_REFRESH_TIME TIMESTAMP_TZ,
    LAST_REFRESH_STATE VARCHAR,
    SUSPENSION_REASON VARCHAR,
    LAST_REFRESH_STATE_MESSAGE VARCHAR,
    SECONDS_BEHIND NUMBER(38,0),
    CHECKED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
