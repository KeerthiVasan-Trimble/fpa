-- DT refresh status monitor: latest-status view with calculation completed flag
-- Co-authored with CoCo
USE ROLE FIELD_SYSTEMS_DEVELOPER_ROLE;

USE DATABASE FIELD_SYSTEMS_EDW;
USE SCHEMA GENERAL;

USE WAREHOUSE FIELD_SYSTEMS_GENERAL_WAREHOUSE;

CREATE OR REPLACE VIEW FIELD_SYSTEMS_EDW.GENERAL.V_REFRESH_STATUS_MONITOR AS
WITH latest_status AS (
    SELECT
        DYNAMIC_TABLE_NAME,
        SCHEMA_NAME,
        SCHEDULING_STATE,
        DATA_TIMESTAMP,
        LAST_REFRESH_TIME,
        LAST_REFRESH_STATE,
        SUSPENSION_REASON,
        LAST_REFRESH_STATE_MESSAGE,
        SECONDS_BEHIND,
        CHECKED_AT
    FROM FIELD_SYSTEMS_EDW.GENERAL.DT_REFRESH_STATUS_MONITOR
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY DYNAMIC_TABLE_NAME, SCHEMA_NAME
        ORDER BY CHECKED_AT DESC
    ) = 1
),
live_timestamps AS (
    SELECT NAME, SCHEMA_NAME, LATEST_DATA_TIMESTAMP
    FROM TABLE(FIELD_SYSTEMS_EDW.INFORMATION_SCHEMA.DYNAMIC_TABLES())
),
input_freshness AS (
    SELECT MAX(LATEST_DATA_TIMESTAMP) AS LAST_INPUT_TIMESTAMP
    FROM TABLE(FIELD_SYSTEMS_EDW.INFORMATION_SCHEMA.DYNAMIC_TABLES())
    WHERE SCHEMA_NAME = 'USER_INPUT'
)
SELECT
    ls.DYNAMIC_TABLE_NAME,
    ls.SCHEMA_NAME,
    ls.SCHEDULING_STATE,
    ls.DATA_TIMESTAMP,
    ls.LAST_REFRESH_TIME,
    ls.LAST_REFRESH_STATE,
    ls.SUSPENSION_REASON,
    ls.LAST_REFRESH_STATE_MESSAGE,
    ls.SECONDS_BEHIND,
    CASE
        WHEN lt.LATEST_DATA_TIMESTAMP >= inp.LAST_INPUT_TIMESTAMP THEN 'Yes'
        ELSE 'No'
    END AS CALCULATION_COMPLETED,
    ls.CHECKED_AT
FROM latest_status ls
LEFT JOIN live_timestamps lt
    ON ls.DYNAMIC_TABLE_NAME = lt.NAME AND ls.SCHEMA_NAME = lt.SCHEMA_NAME
CROSS JOIN input_freshness inp;

GRANT SELECT ON VIEW FIELD_SYSTEMS_EDW.GENERAL.V_REFRESH_STATUS_MONITOR
    TO ROLE SIGMA_INTEGRATION_ROLE;
